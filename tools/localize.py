#!/usr/bin/env python3
"""HomePad's translations: Resources/<code>.lproj/Localizable.strings.

    tools/localize.py keys      print every text the app can show (the compiler finds them: SwiftUI Text("…"),
                                String(localized: "…")), as JSON {text: "file:line"}
    tools/localize.py check     report, per language, texts with no translation, translations nobody uses any more,
                                and translations whose %@ / %lld placeholders don't match the English
    tools/localize.py write     rewrite every language's file from tools/translations/<code>.json (keeping the
                                order of `keys`), and en.lproj with the English itself

The English text in the code is the key. A translation keeps the placeholders of its key, in any order, written
%1$@, %2$lld … when they move, and its ⟦macOS names⟧ exactly as they are (in English): HomePad fills them in from the
Mac's own language. Each such name is also a text of its own, translated as macOS shows it in that language. Run `check` after changing any text in the code.
"""
import glob, json, os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "Resources")
SRC = os.path.join(ROOT, "tools", "translations")
CODES = ["ar", "bn", "de", "es", "fa", "fil", "fr", "hi", "id", "it", "ja", "ko", "pt-BR", "ru", "te", "th", "tr", "vi", "zh-Hans"]


def keys():
    with tempfile.TemporaryDirectory() as out:
        # A clean build of the target, so every file is compiled and reports its texts.
        subprocess.run(["swift", "build", "--scratch-path", os.path.join(out, "build"),
                        "-Xswiftc", "-emit-localized-strings", "-Xswiftc", "-emit-localized-strings-path", "-Xswiftc", out],
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        found = {}
        for f in sorted(glob.glob(os.path.join(out, "*.stringsdata"))):
            data = json.load(open(f))
            for entries in data.get("tables", {}).values():
                for e in entries:
                    found.setdefault(e["key"], f'{os.path.basename(data["source"])}:{e["location"]["startingLine"]}')
        ordered = dict(sorted(found.items(), key=lambda kv: (kv[1].split(":")[0], int(kv[1].split(":")[1]))))
        for k, text in INFO_PLIST.items():
            ordered.setdefault(text, "Info.plist:" + k)
        # Each ⟦macOS name⟧ is a text of its own: the name as macOS shows it in that language (Localization.Mac).
        for k in list(ordered):
            for name in MAC_NAME.findall(k):
                ordered.setdefault(name, "macOS name in: " + ordered[k])
        return ordered


# Texts outside the Swift code: Info.plist keys (written to InfoPlist.strings), with their English.
INFO_PLIST = {"NSAppleEventsUsageDescription": "HomePad asks Finder to empty the Trash, as the Dock does."}


MAC_NAME = re.compile(r"⟦([^⟧]+)⟧")


PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|d|f|\.\df)")


def placeholders(s):
    """The placeholder types in order of their argument number."""
    found, n = {}, 0
    for m in PLACEHOLDER.finditer(s.replace("%%", "")):
        n += 1
        found[int(m.group(1)) if m.group(1) else n] = m.group(2)
    return [found[k] for k in sorted(found)]


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_strings(path, pairs):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("/* Generated by tools/localize.py from tools/translations. Edit those files, not this one. */\n\n")
        for k, v in pairs:
            f.write(f'"{escape(k)}" = "{escape(v)}";\n')


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    all_keys = keys()
    if cmd == "keys":
        json.dump(all_keys, sys.stdout, ensure_ascii=False, indent=1)
        print()
        return
    problems = 0
    for code in CODES:
        path = os.path.join(SRC, code + ".json")
        table = json.load(open(path)) if os.path.exists(path) else {}
        missing = [k for k in all_keys if k not in table]
        unused = [k for k in table if k not in all_keys]
        wrong = [k for k in all_keys if k in table and (placeholders(k) != placeholders(table[k])
                 or sorted(MAC_NAME.findall(k)) != sorted(MAC_NAME.findall(table[k])))]
        for label, items in (("no translation", missing), ("unused", unused), ("placeholders or ⟦macOS names⟧ differ", wrong)):
            for k in items:
                problems += 1
                print(f"{code}: {label}: {k!r}" + (f" ({all_keys[k]})" if k in all_keys else ""))
        if cmd == "write":
            write_strings(os.path.join(RES, code + ".lproj", "Localizable.strings"),
                          [(k, table[k]) for k in all_keys if k in table and k not in wrong])
            write_strings(os.path.join(RES, code + ".lproj", "InfoPlist.strings"),
                          [(k, table.get(text, text)) for k, text in INFO_PLIST.items()])
    if cmd == "write":
        write_strings(os.path.join(RES, "en.lproj", "Localizable.strings"), [(k, k) for k in all_keys])
    print(f"{len(all_keys)} texts, {problems} problems")
    sys.exit(1 if problems and cmd == "check" else 0)


if __name__ == "__main__":
    main()
