import AppKit

/// Text recently copied, for the clipboard filter in the search bar. Kept in memory only (never written to
/// disk), for the last 8 hours and 50 items, and items that password managers mark as secret are skipped.
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let enabledKey = "clipboardHistory"

    struct Item: Identifiable {
        let id = UUID()
        let text: String
        let date: Date
    }

    private(set) var items: [Item] = []
    private var lastChange = NSPasteboard.general.changeCount
    private let maxItems = 50
    private let maxAge: TimeInterval = 8 * 3600
    /// Pasteboard types that apps use to say "don't record this" (the nspasteboard.org convention).
    private let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    static var enabled: Bool { UserDefaults.standard.object(forKey: enabledKey) as? Bool ?? true }

    private init() {
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
    }

    /// Newest first, without anything older than eight hours.
    var recent: [Item] {
        guard Self.enabled else { return [] }
        items.removeAll { Date().timeIntervalSince($0.date) > maxAge }
        return items
    }

    func clear() { items = [] }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard Self.enabled else { items = []; return }
        let types = board.types?.map(\.rawValue) ?? []
        guard !types.contains(where: secretTypes.contains),
              let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty, text.count <= 20_000 else { return }
        items.removeAll { $0.text == text }
        items.insert(Item(text: text, date: Date()), at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }
}

/// The user's Shortcuts (Shortcuts app), listed and run through the `shortcuts` command-line tool.
enum ShortcutsCatalog {
    private static var cache: (names: [String], date: Date)?

    /// Cached names right away (if any), then fresh ones from the tool.
    static func load(completion: @escaping ([String]) -> Void) {
        if let cache, Date().timeIntervalSince(cache.date) < 30 { completion(cache.names); return }
        DispatchQueue.global(qos: .userInitiated).async {
            let names = run(["list"])?.split(separator: "\n").map(String.init).filter { !$0.isEmpty } ?? []
            DispatchQueue.main.async {
                cache = (names, Date())
                completion(names)
            }
        }
    }

    static var cachedNames: [String] { cache?.names ?? [] }

    static func perform(_ name: String) {
        DispatchQueue.global(qos: .userInitiated).async { _ = run(["run", name]) }
    }

    private static func run(_ arguments: [String]) -> String? {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/shortcuts")
        process.arguments = arguments
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = Pipe()
        guard (try? process.run()) != nil else { return nil }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return String(data: data, encoding: .utf8)
    }
}
